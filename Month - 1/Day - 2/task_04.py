'''
Write the algorithm only.

Problem

Ask the user for a number.

If the number is greater than 0:

Positive Number

Otherwise:

Not Positive
'''

'''
Algorithm - 

Ask the user for a number and store it in num.
Check if num is greater than 0.
If True, print Positive Number.
Otherwise, print Not Positive.

'''

num = int(input("Write a number: "))

if num > 0:
    print("Positive")

else:
    print("Not Positive")